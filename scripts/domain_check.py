"""Did CLINC150's teacher suffer from a banking prompt? (Phase 5, 2026-11-06)

    DISTILROUTE_DATASET=clinc150 python scripts/label.py --split test --seed 0 --limit 200 \\
        --top-k 3 --run gate_domain
    DISTILROUTE_DATASET=clinc150 python scripts/domain_check.py

Every CLINC150 label was made with the teacher prompt's first line written for Banking77 ("You
route customer messages sent to a banking app's support inbox"), and its answer-format examples
were Banking77 intent names. CLINC150 spans 10 domains, so that line was wrong for most of it.
This re-asks the question on the first 200 test queries of the labeller's seed-0 shuffle (a
random sample, in the same batches of 20) with the dataset's own line (`data.DOMAINS`) and its
own intent names as examples; everything else is unchanged.

- **banking arm**: those 200 rows of `test.jsonl`, the published labels.
- **domain arm**: the same queries relabelled (`test.gate_domain.jsonl`).

Works on however many of the 200 the domain arm has so far, and says so.
Writes results/clinc150/domain_check.json and docs/clinc150/domain_check.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from distilroute.data import DATASET, DOCS, LABELS, RESULTS, load_labels, load_split, rel  # noqa: E402

N = 200


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
    if DATASET != "clinc150":
        sys.exit("run with DISTILROUTE_DATASET=clinc150")
    if not (LABELS / "test.gate_domain.jsonl").exists():
        sys.exit("test.gate_domain.jsonl not found: run label.py --run gate_domain first")
    first = [
        json.loads(line)["idx"]
        for line in (LABELS / "test.jsonl").open(encoding="utf-8")
        if line.strip()
    ][:N]
    banking = load_labels("test").loc[first]
    dom = load_labels("test.gate_domain")
    idx = [i for i in first if i in dom.index]
    gold = load_split("test").category.reindex(idx).values
    ok_b, ok_d = banking.loc[idx].teacher.values == gold, dom.loc[idx].teacher.values == gold
    rng = np.random.default_rng(0)
    diffs = np.array(
        [
            ok_d[s].mean() - ok_b[s].mean()
            for s in (rng.integers(0, len(idx), len(idx)) for _ in range(10_000))
        ]
    )
    lo, hi = float(np.quantile(diffs, 0.025)), float(np.quantile(diffs, 0.975))
    out = {
        "n": len(idx),
        "planned": N,
        "banking": float(ok_b.mean()),
        "domain": float(ok_d.mean()),
        "gap": float(ok_d.mean() - ok_b.mean()),
        "gap_ci95": [lo, hi],
        "same_answer": float(
            (banking.loc[idx].teacher.values == dom.loc[idx].teacher.values).mean()
        ),
        "only_domain_right": int((ok_d & ~ok_b).sum()),
        "only_banking_right": int((ok_b & ~ok_d).sum()),
    }
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "domain_check.json").write_text(json.dumps(out, indent=2) + "\n")

    partial = f" ({out['n']} of the {N} so far)" if out["n"] < N else ""
    lines = [
        "# Did CLINC150's teacher suffer from a banking prompt?",
        "",
        "_Generated by `scripts/domain_check.py`. Every CLINC150 label was made with a prompt "
        "whose first line describes a banking app's support inbox and whose format examples are "
        "Banking77 intent names. Here the same test queries are relabelled with CLINC150's own "
        "line and examples: same batches, same settings (gpt-oss-120b, top-3, reasoning low). "
        "Accuracy vs gold._",
        "",
        f"| teacher prompt | accuracy on {out['n']} test queries{partial} |",
        "|---|---:|",
        f"| banking line (the published labels) | {out['banking']:.3f} |",
        f"| CLINC150's own line | {out['domain']:.3f} |",
        f"| own − banking | **{out['gap'] * 100:+.1f} pt** "
        f"(95 % {lo * 100:+.1f} to {hi * 100:+.1f}) |",
        "",
        f"The two prompts give the same answer on {out['same_answer']:.1%} of queries; the own "
        f"line is right where the banking one is wrong on {out['only_domain_right']}, and the "
        f"reverse on {out['only_banking_right']}. "
        + (
            "**The banking line made no measurable difference**, so the published CLINC150 "
            "numbers stand; new labels use the dataset's own line."
            if lo <= 0 <= hi
            else "**The prompt line matters here**: read the published CLINC150 teacher numbers "
            "with that gap in mind."
        ),
    ]
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "domain_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"-> {rel(RESULTS)}/domain_check.json, {rel(DOCS)}/domain_check.md")


if __name__ == "__main__":
    main()
